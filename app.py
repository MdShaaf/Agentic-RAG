# new ui
import tempfile
from pathlib import Path

import streamlit as st

from src.document_reader import load_all_documents
from src.Chunking import chunk_documents
from src.Embedding import build_or_load_faiss
from src.Agentic_RAG import run_rag_agent
from src.similarity_reranker import similarity_reranker
from src.Agentic_RAG import DEFAULT_INSTRUCTIONS

# ---------- Page config ----------
st.set_page_config(
    page_title="Document RAG System",
    page_icon="📚",
    layout="wide",
    initial_sidebar_state="expanded",
)

# ---------- Session state ----------
defaults = {
    "vectorstore": None,
    "messages": [],       # chat history: {"role", "content", "sources"}
    "num_files": 0,
    "num_chunks": 0,
    "file_names": [],
    "instructions": DEFAULT_INSTRUCTIONS,

}

for key, value in defaults.items():
    if key not in st.session_state:
        st.session_state[key] = value


def process_pdfs(files):
    """Run the ingestion pipeline: load -> chunk -> embed/index."""
    with tempfile.TemporaryDirectory() as temp_dir:
        for file in files:
            (Path(temp_dir) / file.name).write_bytes(file.getvalue())
        documents = load_all_documents(Path(temp_dir))

    if not documents:
        return False, 0

    chunked_docs = chunk_documents(documents)
    st.session_state.vectorstore = build_or_load_faiss(chunked_docs)
    st.session_state.num_files = len(files)
    st.session_state.num_chunks = len(chunked_docs)
    st.session_state.file_names = [f.name for f in files]
    st.session_state.messages = []  # new knowledge base -> fresh chat
    return True, len(chunked_docs)


# ---------- Sidebar: ingestion + settings ----------
with st.sidebar:
    st.header("📂 Knowledge Base")
    uploaded_files = st.file_uploader(
        "Upload PDF files",
        type=["pdf"],
        accept_multiple_files=True,
        help="You can upload multiple PDFs at once.",
    )

    if st.button("⚙️ Process PDFs", type="primary", use_container_width=True,
                 disabled=not uploaded_files):
        with st.status("Processing documents...", expanded=True) as status:
            st.write("Reading PDFs and building index...")
            ok, n_chunks = process_pdfs(uploaded_files)
            if ok:
                status.update(label=f"Done: {n_chunks} chunks indexed",
                              state="complete", expanded=False)
            else:
                status.update(label="No readable text found", state="error")



    st.divider()
    if st.button("🗑️ Clear chat", use_container_width=True):
        st.session_state.messages = []
        st.rerun()

        st.divider()
    with st.expander("⚙️ Advanced"):
        temperature = st.slider(
            "Temperature", 0.0, 1.0, 0.1, 0.05,
            help="Lower = more factual and consistent. Higher = more varied wording.",
        )
        st.text_area(
            "Answer instructions",
            key="instructions",
            height=120,
            help="Tells the model how to answer. The retrieved context and your question are added automatically.",
        )
        if st.button("Reset instructions", use_container_width=True):
            st.session_state.instructions = DEFAULT_INSTRUCTIONS
            st.rerun()

    st.divider()

    with st.expander("ℹ️ About"):
        st.caption(
            "Upload PDFs, index them into a vector store, and ask questions. "
            "Answers are generated by an agentic RAG pipeline from the "
            "retrieved context."
        )

# ---------- Main area ----------
st.title("📚 Document RAG System")
st.caption("Ask questions about your PDFs and see exactly which context backed each answer.")

if st.session_state.vectorstore is None:
    st.info("👈 Upload PDFs in the sidebar and click **Process PDFs** to begin.")
    st.stop()

# Status metrics
c1, c2, c3 = st.columns(3)
c1.metric("Documents", st.session_state.num_files)
c2.metric("Chunks indexed", st.session_state.num_chunks)
c3.metric("Messages", len(st.session_state.messages))

with st.expander("📄 Loaded files"):
    for name in st.session_state.file_names:
        st.write(f"• {name}")

st.divider()
search_strategy = st.radio("Search strategy", ["Semantic Search", "Keyword Search", "Hybrid Search"], horizontal=True)
if search_strategy == "Semantic Search":
    st.caption(f"Selected: Semantic Search")
    st.caption("Finds relevant content based on the meaning and context of your question, even when exact words differ.")
elif search_strategy == "Keyword Search":
    st.caption(f"Selected: Keyword Search")
    st.caption("Finds content containing matching words or exact terms, useful for technical codes, IDs, and specific keywords.")
else:
    st.caption(f"Selected: Hybrid Search")
    st.caption("Combines semantic and keyword search to find content using both meaning, context and exact terms like codes, IDs, and specific keywords.")
st.divider()

# Chat history
for msg in st.session_state.messages:
    with st.chat_message(msg["role"]):
        st.markdown(msg["content"])
        if msg["role"] == "assistant" and msg.get("sources"):
            with st.expander(f"📎 Sources ({len(msg['sources'])})"):
                for i, src in enumerate(msg["sources"], 1):
                    st.markdown(f"**Chunk {i}** · {src['meta']}")
                    st.caption(src["text"])

# Chat input
if question := st.chat_input("Ask a question about your PDFs..."):
    st.session_state.messages.append({"role": "user", "content": question})
    with st.chat_message("user"):
        st.markdown(question)

    with st.chat_message("assistant"):
        with st.spinner("Retrieving context and generating answer..."):
            results = similarity_reranker(st.session_state.vectorstore.docstore._dict.values(), st.session_state.vectorstore, question, search_strategy)
            st.spinner("Reranked results retrieved. Generating answer...")
            context = "\n\n".join(doc.page_content for doc, score in results)
            answer = run_rag_agent(question, context,temperature=temperature,instructions=st.session_state.instructions)

        st.markdown(answer)

        sources = []
        for i, (doc, score) in enumerate(results, 1):
            meta = doc.metadata or {}
            label = " · ".join(
                str(x) for x in [
                    Path(str(meta.get("source", "unknown"))).name,
                    f"page {meta['page'] + 1}" if isinstance(meta.get("page"), int) else None,
                ] if x
            )
            sources.append({"meta": label, "text": doc.page_content, "score": float(score)})

        with st.expander(f"📎 Sources ({len(sources)})"):
            for i, src in enumerate(sources, 1):
                st.markdown(f"**Chunk {i}** · {src['meta']}")
                st.caption(src["text"])

    st.session_state.messages.append(
        {"role": "assistant", "content": answer, "sources": sources}
    )